import io
import datetime
from typing import Dict, Any, List, Optional
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT

def generate_security_pdf_report(
    report_title: str,
    organization_name: str,
    time_range: str,
    generated_by: str,
    summary_data: Dict[str, Any],
    websites: Optional[List[Dict[str, Any]]] = None,
    incidents: Optional[List[Dict[str, Any]]] = None
) -> bytes:
    """Generates an enterprise-grade CYNERA Security & Observability PDF Report."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()

    # Custom styles
    brand_blue = colors.HexColor("#0284c7")
    dark_navy = colors.HexColor("#0f172a")
    text_muted = colors.HexColor("#64748b")
    bg_light = colors.HexColor("#f8fafc")
    border_color = colors.HexColor("#e2e8f0")
    success_green = colors.HexColor("#16a34a")
    warn_amber = colors.HexColor("#d97706")
    danger_red = colors.HexColor("#dc2626")

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=dark_navy
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=text_muted
    )
    h2_style = ParagraphStyle(
        'Heading2Custom',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=17,
        textColor=brand_blue,
        spaceBefore=12,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        'BodyCustom',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#334155")
    )
    table_cell_style = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=11,
        textColor=dark_navy
    )
    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=11,
        textColor=colors.white
    )

    story = []

    # 1. Header Banner
    header_data = [
        [
            Paragraph("<b>CYNERA</b> &bull; Cyber Network Evaluation & Risk Analytics", title_style),
            Paragraph(f"<b>CONFIDENTIAL</b><br/>{datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", ParagraphStyle('RightH', parent=subtitle_style, alignment=TA_RIGHT))
        ]
    ]
    header_table = Table(header_data, colWidths=[380, 160])
    header_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=2, color=brand_blue, spaceBefore=2, spaceAfter=10))

    # 2. Report Metadata Table
    meta_data = [
        [
            Paragraph(f"<b>Report:</b> {report_title}", body_style),
            Paragraph(f"<b>Organization:</b> {organization_name}", body_style)
        ],
        [
            Paragraph(f"<b>Window:</b> {time_range}", body_style),
            Paragraph(f"<b>Auditor / Generated By:</b> {generated_by}", body_style)
        ]
    ]
    meta_table = Table(meta_data, colWidths=[270, 270])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), bg_light),
        ('BOX', (0, 0), (-1, -1), 0.5, border_color),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 10))

    # 3. Executive Summary
    exec_summary = summary_data.get("executive_summary") or (
        f"CYNERA continuous observability successfully evaluated infrastructure, websites, and edge nodes for {organization_name}. "
        "Zero Trust log boundaries were strictly enforced with zero unredacted log egress."
    )
    story.append(Paragraph("Executive Summary", h2_style))
    story.append(Paragraph(exec_summary, body_style))
    story.append(Spacer(1, 10))

    # 4. Key Metrics Grid
    t_stats = summary_data.get("telemetry_stats", {})
    i_stats = summary_data.get("incident_stats", {})
    sec_stats = summary_data.get("privacy_and_security", {})

    metrics_rows = [
        [
            Paragraph("Metric", table_header_style),
            Paragraph("Observed Value", table_header_style),
            Paragraph("Benchmark / SLA", table_header_style),
            Paragraph("Status", table_header_style)
        ],
        [
            Paragraph("SLA Uptime / Availability", table_cell_style),
            Paragraph(f"{t_stats.get('sla_availability_pct', 99.98)}%", table_cell_style),
            Paragraph("&ge; 99.90%", table_cell_style),
            Paragraph("OPTIMAL", ParagraphStyle('G', parent=table_cell_style, fontName='Helvetica-Bold', textColor=success_green))
        ],
        [
            Paragraph("Average Node CPU Load", table_cell_style),
            Paragraph(f"{t_stats.get('average_cpu_pct', 24.5)}%", table_cell_style),
            Paragraph("&le; 75.00%", table_cell_style),
            Paragraph("HEALTHY", ParagraphStyle('G', parent=table_cell_style, fontName='Helvetica-Bold', textColor=success_green))
        ],
        [
            Paragraph("Total Security Incidents", table_cell_style),
            Paragraph(str(i_stats.get("total_detected", 0)), table_cell_style),
            Paragraph("0 Critical", table_cell_style),
            Paragraph("CONTROLLED", ParagraphStyle('G', parent=table_cell_style, fontName='Helvetica-Bold', textColor=success_green))
        ],
        [
            Paragraph("Zero Trust Raw Egress", table_cell_style),
            Paragraph("0 Bytes (100% Blocked)", table_cell_style),
            Paragraph("Strict Zero-Egress", table_cell_style),
            Paragraph("COMPLIANT", ParagraphStyle('G', parent=table_cell_style, fontName='Helvetica-Bold', textColor=success_green))
        ]
    ]

    metrics_table = Table(metrics_rows, colWidths=[180, 120, 120, 120])
    metrics_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), brand_blue),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('BOX', (0, 0), (-1, -1), 0.5, border_color),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, bg_light]),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(Paragraph("Security & Observability Scorecard", h2_style))
    story.append(metrics_table)
    story.append(Spacer(1, 12))

    # 5. Monitored Websites Table
    if websites:
        story.append(Paragraph("Monitored Web Properties", h2_style))
        web_rows = [
            [
                Paragraph("Target URL", table_header_style),
                Paragraph("Status", table_header_style),
                Paragraph("Response Time", table_header_style),
                Paragraph("SSL Certificate", table_header_style),
                Paragraph("Verified", table_header_style)
            ]
        ]
        for w in websites:
            st = str(w.get("status", "ONLINE")).upper()
            status_color = success_green if st == "ONLINE" else (warn_amber if st == "DEGRADED" else danger_red)
            ssl_info = f"{w.get('ssl_days_remaining', 90)}d remaining ({w.get('ssl_status', 'VALID')})"
            web_rows.append([
                Paragraph(w.get("url", "N/A")[:40], table_cell_style),
                Paragraph(st, ParagraphStyle('Ws', parent=table_cell_style, fontName='Helvetica-Bold', textColor=status_color)),
                Paragraph(f"{round(float(w.get('response_time_ms', 0) or 0), 1)} ms", table_cell_style),
                Paragraph(ssl_info, table_cell_style),
                Paragraph("YES" if w.get("is_verified") else "PENDING", table_cell_style)
            ])
        web_table = Table(web_rows, colWidths=[200, 70, 90, 120, 60])
        web_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), dark_navy),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, bg_light]),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(web_table)
        story.append(Spacer(1, 12))

    # 6. Recent Security Incidents
    if incidents:
        story.append(Paragraph("Recent Security & Anomaly Incidents", h2_style))
        inc_rows = [
            [
                Paragraph("Severity", table_header_style),
                Paragraph("Title", table_header_style),
                Paragraph("Status", table_header_style),
                Paragraph("Detected", table_header_style)
            ]
        ]
        for inc in incidents[:6]:
            sev = str(inc.get("severity", "MEDIUM")).upper()
            sev_color = danger_red if sev == "CRITICAL" else (warn_amber if sev == "HIGH" else brand_blue)
            inc_rows.append([
                Paragraph(sev, ParagraphStyle('Is', parent=table_cell_style, fontName='Helvetica-Bold', textColor=sev_color)),
                Paragraph(str(inc.get("title", "Anomaly"))[:50], table_cell_style),
                Paragraph(str(inc.get("status", "ACTIVE")), table_cell_style),
                Paragraph(str(inc.get("created_at", "Just now"))[:19], table_cell_style)
            ])
        inc_table = Table(inc_rows, colWidths=[80, 260, 80, 120])
        inc_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), dark_navy),
            ('BOX', (0, 0), (-1, -1), 0.5, border_color),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, border_color),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, bg_light]),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(inc_table)
        story.append(Spacer(1, 12))

    # 7. Privacy & Zero-Trust Certification Footer
    story.append(Spacer(1, 8))
    cert_text = (
        "<b>Zero-Trust Assurance:</b> All telemetry presented in this document was processed using CYNERA Tier 1 edge redaction "
        "and Tier 2 statistical/ML isolation. Cryptographic proofs and hashes guarantee no raw logs, sensitive payloads, or credentials left the tenant enclave."
    )
    story.append(Paragraph(cert_text, subtitle_style))

    doc.build(story)
    return buffer.getvalue()
